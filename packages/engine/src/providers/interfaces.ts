import type { BrandProfile } from "@/domain/brand";
import type { PlateRequest, PlateResult, Product } from "@/domain/product";
import type { Recipe } from "@/domain/recipe";
import type { BaseUnderstanding } from "@/domain/understanding";
import type { VariantDirection } from "@/domain/variant-direction";
import type {
  Capabilities,
  GenerationResult,
  GenerationUsage,
  ImageComposeInput,
  ImageEditInput,
  ImageGenInput,
} from "@/providers/types";

export type ProviderId = "google" | "openai";

// (a) Vision / analysis: MasterAsset -> BaseUnderstanding (structured, Zod-validated).
export interface VisionProvider {
  analyze(input: { assetUrl: string }): Promise<BaseUnderstanding>;
}

// (b) Art director: text model -> diverse per-direction creative specs (scene,
// composition, lighting), orthogonal not variations. buildCards combines these
// with the shared planning (subject + palette) into the cards.
export interface ArtDirector {
  proposeDirections(input: {
    understanding: BaseUnderstanding;
    recipe: Recipe;
    brand: BrandProfile;
    n: number;
  }): Promise<VariantDirection[]>;
}

// (c) Image executor.
export interface ImageProvider {
  readonly id: ProviderId;
  readonly capabilities: Capabilities;
  generate(input: ImageGenInput): Promise<GenerationResult>;
  edit(input: ImageEditInput): Promise<GenerationResult>;
  compose(input: ImageComposeInput): Promise<GenerationResult>;
  // The queue's edit: the generated bytes and usage, nothing stored. The queue
  // records the cost first, then stores the bytes (and retries only the
  // storage if that fails, never the paid call). Bounded and not retried by the
  // SDK: the queue owns retries. `beforeCall` runs right before the paid
  // request, after anything free (fetching the reference); if it throws, no
  // request is made.
  editBytes?(
    input: ImageEditInput,
    options: { timeoutMs: number; beforeCall?: () => Promise<void> },
  ): Promise<EditBytesResult>;
}

// A provider answer: `bytes` is null when it returned no image (still paid,
// so the usage is kept).
export interface EditBytesResult {
  bytes: Uint8Array | null;
  mime: string;
  model: string;
  usage?: GenerationUsage;
}

// (d) Video executor (image-to-video).
export interface VideoProvider {
  readonly id: ProviderId;
  animate(input: {
    startFrameAssetId: string;
    prompt: string;
    motion: string;
    durationSec: number;
    model: ModelConfigLike;
  }): Promise<GenerationResult>;
}

// Structural mirror of ModelConfig's fields the video adapters read — keeps this
// interfaces module free of a schema import.
export interface ModelConfigLike {
  provider: ProviderId;
  model: string;
  aspect: string;
}

// (e) Plate renderer: (product, request) -> an exact reference image of the real
// product with the buyer's wording, plus the QC hints the verifier needs. Must be
// deterministic for the same input, opaque, and render the wording verbatim
// (fonts from the product spec, never drawn by an image model).
export interface PlateRenderer {
  readonly id: string;
  readonly version: string;
  render(input: {
    product: Product;
    request: PlateRequest;
  }): Promise<PlateResult>;
}

// (f) Product catalog adapter: where a maker's products come from. maker #1's code
// catalog is the first implementation; a maker without a catalog gets one built
// from the product form or from a traced SVG (source.kind = "vector").
export interface ProductCatalogAdapter {
  readonly id: string;
  list(): Promise<Product[]>;
  get(ref: string): Promise<Product | null>;
  renderer(): PlateRenderer;
}
