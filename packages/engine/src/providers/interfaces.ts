import type { BrandProfile } from "@/domain/brand";
import type { ProviderId, VideoResolution } from "@/domain/model-defaults";
import type { PlateRequest, PlateResult, Product } from "@/domain/product";
import type { Recipe } from "@/domain/recipe";
import type { BaseUnderstanding } from "@/domain/understanding";
import type { VariantDirection } from "@/domain/variant-direction";
import type { ProductDraft } from "@/providers/text-prompts";
import type {
  Capabilities,
  GenerationResult,
  GenerationUsage,
  ImageComposeInput,
  ImageEditInput,
  ImageGenInput,
} from "@/providers/types";

export type { ProviderId };

// A text call (vision, art direction): the provider's text model to run (from
// the catalog) and `beforeCall`, run right before the one paid request, like
// the image and video calls. The answer carries the usage it reported.
export interface TextCallOptions {
  model: string;
  beforeCall?: () => Promise<void>;
}

export interface TextResult<T> {
  value: T;
  model: string;
  usage?: GenerationUsage;
}

// (a) Vision / analysis: MasterAsset -> BaseUnderstanding (structured,
// Zod-validated). A failed call throws; the caller decides and says it
// degraded (never a silent stand-in).
export interface VisionProvider {
  analyze(
    input: { assetUrl: string },
    options: TextCallOptions,
  ): Promise<TextResult<BaseUnderstanding>>;
  // A product form drafted from one photo of the piece (the maker reviews it).
  draftProduct(
    input: { assetUrl: string },
    options: TextCallOptions,
  ): Promise<TextResult<ProductDraft>>;
}

// (b) Art director: text model -> diverse per-direction creative specs (scene,
// composition, lighting), orthogonal not variations. buildCards combines these
// with the shared planning (subject + palette) into the cards.
export interface ArtDirector {
  proposeDirections(
    input: {
      understanding: BaseUnderstanding;
      recipe: Recipe;
      brand: BrandProfile;
      n: number;
    },
    options: TextCallOptions,
  ): Promise<TextResult<VariantDirection[]>>;
}

// A direct (studio) paid call: `beforeCall` runs right before the paid request
// (the cap reservation marks it there); if it throws, no request is made.
export interface DirectCallOptions {
  beforeCall?: () => Promise<void>;
}

// (c) Image executor.
export interface ImageProvider {
  readonly id: ProviderId;
  readonly capabilities: Capabilities;
  generate(
    input: ImageGenInput,
    options?: DirectCallOptions,
  ): Promise<GenerationResult>;
  edit(
    input: ImageEditInput,
    options?: DirectCallOptions,
  ): Promise<GenerationResult>;
  compose(
    input: ImageComposeInput,
    options?: DirectCallOptions,
  ): Promise<GenerationResult>;
  // The queue's edit: the generated bytes and usage, nothing stored. The queue
  // records the cost first, then stores the bytes (and retries only the
  // storage if that fails, never the paid call). Bounded and not retried by the
  // SDK: the queue owns retries. `beforeCall` runs right before the paid
  // request, after anything free (fetching the reference); if it throws, no
  // request is made.
  editBytes?(
    input: ImageEditInput,
    options: { timeoutMs: number; beforeCall?: () => Promise<void> },
  ): Promise<EditBytesResult>;
}

// A provider answer: `bytes` is null when it returned no image (still paid,
// so the usage is kept); `refusal` says why when the provider did.
export interface EditBytesResult {
  bytes: Uint8Array | null;
  mime: string;
  model: string;
  usage?: GenerationUsage;
  refusal?: string;
}

// (d) Video executor (image-to-video). `beforeCall` runs right before the paid
// request (the spend row marks it), like the image edit's. `animate` stores
// the clip (the studio); `animateBytes` returns it unstored (the queue records
// its cost first, then stores it with retries — never the paid call).
export interface AnimateRequest {
  startFrameAssetId: string;
  prompt: string;
  motion: string;
  durationSec: number;
  negative?: string;
  model: ModelConfigLike;
}

export interface VideoBytesResult {
  bytes: Uint8Array;
  mime: string;
  model: string;
  // The seconds rendered (what the clip is billed by).
  seconds: number;
}

export interface VideoProvider {
  readonly id: ProviderId;
  animate(
    input: AnimateRequest,
    options?: { beforeCall?: () => Promise<void> },
  ): Promise<GenerationResult>;
  animateBytes?(
    input: AnimateRequest,
    options?: { beforeCall?: () => Promise<void> },
  ): Promise<VideoBytesResult>;
}

// Structural mirror of ModelConfig's fields the video adapters read — keeps this
// interfaces module free of a schema import.
export interface ModelConfigLike {
  provider: ProviderId;
  model: string;
  aspect: string;
  resolution?: VideoResolution;
}

// (e) Plate renderer: (product, request) -> an exact reference image of the real
// product with the buyer's wording, plus the QC hints the verifier needs. Must be
// deterministic for the same input, opaque, and render the wording verbatim
// (fonts from the product spec, never drawn by an image model).
export interface PlateRenderer {
  readonly id: string;
  readonly version: string;
  render(input: {
    product: Product;
    request: PlateRequest;
  }): Promise<PlateResult>;
}

// (f) Product catalog adapter: where a maker's products come from. A maker's own
// code catalog is one implementation; a maker without a catalog gets one built
// from the product form or from a traced SVG (source.kind = "vector").
export interface ProductCatalogAdapter {
  readonly id: string;
  list(): Promise<Product[]>;
  get(ref: string): Promise<Product | null>;
  renderer(): PlateRenderer;
}
